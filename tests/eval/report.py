#!/usr/bin/env python3
"""Aggregate tests/eval/out/*.results.json into tests/eval/RESULTS.md.

Reports, per config and task: accuracy per LoopCD condition, the delta vs `off`, the mean tokens/second,
and the seconds per item. Prints the paper's numbers as a scale reference and states the honesty caveats.
"""
import json
from pathlib import Path

CONDITIONS = ["off", "logits", "logits_adaptive", "hidden"]

PAPER = {
    "math": ("AIME 2024 pass@1, 30 problems x 16 samples (Ouro-2.6B-Thinking)",
             {"off": "61.88%", "logits": "70.62%", "logits_adaptive": "73.33%"}),
    "mc": ("seven-benchmark mean (Ouro-2.6B), Table 2",
           {"off": "baseline", "logits": "+0.84 pts", "logits_adaptive": "+0.95 pts"}),
    "gen": ("HumanEval base pass@1 (Ouro-2.6B), Table 1(b)",
            {"off": "75.61%", "logits": "77.44%", "logits_adaptive": "79.88%"}),
}


def agg(results, task, cond):
    rows = [r for r in results["items"] if r["task"] == task and r["condition"] == cond]
    if not rows:
        return None
    n = len(rows)
    acc = sum(1 for r in rows if r["ok"]) / n
    tok = sum((r["completion_tokens"] or 0) for r in rows)
    sec = sum(r["elapsed_s"] for r in rows) or 1e-9
    return {"n": n, "acc": acc, "tokens": tok, "sec": sec,
            "tok_s": tok / sec, "sec_per_item": sec / n}


def main():
    root = Path(".")
    outdir = root / "tests/eval/out"
    configs = [c["name"] for c in json.loads((root / "tests/eval/configs.json").read_text())["configs"]]

    lines = []
    lines.append("# loopcd M5 - LoopCD on-vs-off measurement results\n")
    lines.append("Generated by `tests/eval/report.py` from `tests/eval/out/*.results.json`.\n")

    lines.append("## What this measures (and what it does not)\n")
    lines.append("- A tiny pinned task set (4 math, 5 multiple-choice, 2 generation), **greedy decoding, "
                 "one sample per item**. Accuracy moves in coarse steps (one item = 20-25%) and the deltas "
                 "are noisy.\n")
    lines.append("- These are **not** the paper's numbers. The paper's AIME pass@1 uses 30 problems and 16 "
                 "samples; the paper values below are a direction/scale reference, not a pass/fail bar.\n")
    lines.append("- `LoopCD-Hidden` is meaningful only on `f32_clean` (f32 weights + f32 KV). On the "
                 "shipping stack (`Q4_K_M` + `q8_0`) it is known to degenerate to a repeating token, so the "
                 "shipping `hidden` row is reported for honesty, not as a reproduction.\n")
    lines.append("- Conditions: `off`; `logits` (fixed omega from the paper's per-task preset); "
                 "`logits_adaptive` (paper cap); `hidden` (fixed omega = 0.5).\n")

    for c in configs:
        p = outdir / f"{c}.results.json"
        if not p.exists():
            lines.append(f"\n## Config `{c}`\n\n(no results yet: run `tests/eval/run_eval.py --config {c}`)\n")
            continue
        res = json.loads(p.read_text())
        lines.append(f"\n## Config `{c}` - `{res['model']}` on `{res['device']}`, KV `{res['kv_type']}`\n")
        for task in ("math", "mc", "gen"):
            lines.append(f"\n### {task}\n")
            lines.append("| condition | n | accuracy | delta vs off | tokens | tok/s | s/item |")
            lines.append("|---|---|---|---|---|---|---|")
            base = agg(res, task, "off")
            for cond in CONDITIONS:
                a = agg(res, task, cond)
                if a is None:
                    continue
                delta = "" if cond == "off" else f"{(a['acc'] - base['acc']) * 100:+.1f} pts"
                lines.append(f"| {cond} | {a['n']} | {a['acc'] * 100:.1f}% | {delta} | {a['tokens']} | "
                             f"{a['tok_s']:.2f} | {a['sec_per_item']:.1f} |")
            metric, ref = PAPER[task]
            lines.append(f"\nPaper reference ({metric}): " + ", ".join(f"{k}={v}" for k, v in ref.items()) + ".\n")
        lines.append("\n**Reading this config:** " +
                     ("LoopCD-Hidden is meaningful here; the logits/hidden deltas are the cleanest signal."
                      if c == "f32_clean" else
                      "The `hidden` row is expected to be degenerate; only the `logits` rows support a claim about the shipping stack.") + "\n")

    # R=4 vs R=2 comparison (shipping stack) when both runs exist.
    p4 = outdir / "shipping.results.json"
    p2 = outdir / "shipping_r2.results.json"
    if p4.exists() and p2.exists():
        r4 = json.loads(p4.read_text())
        r2 = json.loads(p2.read_text())
        lines.append("\n## R=4 vs R=2 (halved recurrent depth, shipping stack)\n")
        lines.append("`--loops 2` halves the recurrent depth - the paper's compute-saving regime, where LoopCD "
                     "is meant to recover the accuracy lost to the halving. Same items, same conditions; "
                     "the `tok/s` columns show the speed change directly.\n")
        for task in ("math", "mc", "gen"):
            lines.append(f"\n### {task}\n")
            lines.append("| condition | R=4 acc | R=2 acc | acc delta (R2-R4) | R=4 tok/s | R=2 tok/s |")
            lines.append("|---|---|---|---|---|---|")
            for cond in CONDITIONS:
                a4 = agg(r4, task, cond)
                a2 = agg(r2, task, cond)
                if a4 is None and a2 is None:
                    continue
                acc4 = f"{a4['acc'] * 100:.1f}%" if a4 else "-"
                acc2 = f"{a2['acc'] * 100:.1f}%" if a2 else "-"
                delta = f"{(a2['acc'] - a4['acc']) * 100:+.1f} pts" if (a4 and a2) else "-"
                t4 = f"{a4['tok_s']:.2f}" if a4 else "-"
                t2 = f"{a2['tok_s']:.2f}" if a2 else "-"
                lines.append(f"| {cond} | {acc4} | {acc2} | {delta} | {t4} | {t2} |")
        lines.append("")

    (root / "tests/eval/RESULTS.md").write_text("\n".join(lines) + "\n")
    print("wrote tests/eval/RESULTS.md")


if __name__ == "__main__":
    main()
